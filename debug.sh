# Noise Ordnance — quick debug build for testing changes/fixes/new features.
#
# Assumes third_party/ is already installed and patched (run
# third_party/install-third-party.sh first if not).
#
# Builds with DEBUG=true (debug logging enabled, -g -O0), installs
# LV2 + VST3 bundles to ~/.lv2 and ~/.vst3 without prompting.
#
# Usage: bash debug.sh  (from the project root)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

echo "=== Noise Ordnance: debug build ==="
make DEBUG=true -j"$(nproc)"
# LV2 TTLs aren't generated by make in this tree, so do it explicitly.
# The generator binary only needs building once.
if [ ! -x third_party/dpf/utils/lv2_ttl_generator ]; then
  cc third_party/dpf/utils/lv2-ttl-generator/lv2_ttl_generator.c -o third_party/dpf/utils/lv2_ttl_generator -ldl
fi
bash third_party/dpf/utils/generate-ttl.sh third_party/bin

echo "=== Noise Ordnance: installing debug bundles ==="
mkdir -p "$HOME/.lv2" "$HOME/.vst3"
rm -rf "$HOME/.lv2/NoiseOrdnance.lv2" "$HOME/.vst3/NoiseOrdnance.vst3"
cp -a "$ROOT/third_party/bin/NoiseOrdnance.lv2" "$HOME/.lv2/"
cp -a "$ROOT/third_party/bin/NoiseOrdnance.vst3" "$HOME/.vst3/"

echo "Installed:"
ls -ld "$HOME/.lv2/NoiseOrdnance.lv2" "$HOME/.vst3/NoiseOrdnance.vst3"
echo ""
echo "=== done ==="
echo "Debug logging (if any) writes to /tmp/no-debug.log"
echo "Remove the plugin instance in Ardour and re-add to pick up the new build."
